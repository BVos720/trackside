/*
 * Turn the scenery PNGs into a TypeScript module of data URIs.
 *
 * ── Why the WebView needs this and the native map does not ────────────────
 * The native map hands MapLibre the bundled PNGs directly, through
 * `<Images images={SCENERY_SPRITES} />`. The 3D map is a WebView with no
 * sprite sheet and no access to the app's files, so those same layers drew
 * nothing at all — "Image tree could not be loaded", once per kind, and a
 * circuit with no trees on it.
 *
 * Inlining is affordable here in a way it would not be for the basemap: all
 * four sprites together are under two kilobytes, so they cost less than the
 * request that would fetch them. It also keeps them offline, which a hosted
 * sprite URL would not.
 *
 * Run `node scripts/write-scenery-sprites.mjs` after `npm run sprites`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KINDS = ['tree', 'shrub', 'grass', 'rock'];

const entries = KINDS.map((kind) => {
  const png = readFileSync(join(ROOT, 'assets/sprites', kind + '.png'));
  return `  ${kind}: 'data:image/png;base64,${png.toString('base64')}',`;
});

const out = `/*
 * Generated by scripts/write-scenery-sprites.mjs — do not edit by hand.
 *
 * The scenery sprites as data URIs, for the 3D map's WebView. It has no sprite
 * sheet and cannot read the app's files, so these are the only way those layers
 * get their icons. Under two kilobytes in total, and offline by construction.
 *
 * Regenerate after changing anything in assets/sprites.
 */
export const SCENERY_DATA_URIS: Record<string, string> = {
${entries.join('\n')}
};
`;

const target = join(ROOT, 'src/ui/map/scenerySprites.ts');
writeFileSync(target, out);
console.log(
  'wrote src/ui/map/scenerySprites.ts —',
  KINDS.length,
  'sprites,',
  out.length,
  'chars',
);
