// Embed exactly the same modules used by web. Hermes cannot serialize function source.
import fs from 'node:fs';
import ts from 'typescript';

const modules = {
  shadows: 'src/core/logic/sceneShadows.ts',
  shaders: 'src/ui/map/atmosphereShaders.ts',
  runtime: 'src/ui/map/sceneLighting.ts',
};
const compiled = Object.entries(modules).map(([id, file]) => {
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
  }).outputText;
  return `${JSON.stringify(id)}: function(module, exports, require) {\n${code}\n}`;
}).join(',\n');
const source = `function(map, MercatorCoordinate, options) {
  var modules = {${compiled}};
  var cache = {};
  var aliases = { '../../core/logic/sceneShadows': 'shadows', './atmosphereShaders': 'shaders' };
  function load(id) {
    id = aliases[id] || id;
    if (!cache[id]) { var module = { exports: {} }; cache[id] = module; modules[id](module, module.exports, load); }
    return cache[id].exports;
  }
  return load('runtime').installSceneLighting(map, MercatorCoordinate, options);
}`;
const output = `// Generated by node scripts/build-scene-lighting.mjs. Do not edit.\nexport const SCENE_LIGHTING_SOURCE = ${JSON.stringify(source)};\n`;
const target = 'src/ui/map/sceneLightingSource.ts';
if (process.argv.includes('--check') || new URL(import.meta.url).searchParams.has('check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Scene lighting bridge is stale. Run node scripts/build-scene-lighting.mjs');
  console.log('Native scene lighting matches the web source.');
} else {
  fs.writeFileSync(target, output);
  console.log(`Generated ${target}`);
}
